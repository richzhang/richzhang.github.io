#!/usr/bin/env python3
"""Apply the editable publication-topics.csv table to the JSON and browser data."""

import argparse
import csv
import json
from pathlib import Path


def read_assignments(path, data):
    topics = {topic["id"]: topic for topic in data["topics"]}
    papers = {paper["id"]: paper for paper in data["papers"]}
    assignments = {}

    with path.open(encoding="utf-8-sig", newline="") as source:
        reader = csv.DictReader(source, strict=True)
        columns = ["id", "year", "title"] + [topic["label"] for topic in topics.values()]
        if not reader.fieldnames or sorted(reader.fieldnames) != sorted(columns):
            raise ValueError("CSV must have id, year, title, and one column for each keyword.")
        for row in reader:
            location = f"CSV line {reader.line_num}"
            if None in row or any(value is None for value in row.values()):
                raise ValueError(f"{location}: expected exactly {len(columns)} columns.")
            paper_id = row["id"].strip()
            if paper_id not in papers:
                raise ValueError(f"{location}: unknown paper ID {paper_id!r}.")
            if paper_id in assignments:
                raise ValueError(f"{location}: duplicate paper ID {paper_id!r}.")
            paper = papers[paper_id]
            if row["year"].strip() != str(paper["year"]) or row["title"].strip() != paper["title"]:
                raise ValueError(f"{location}: keep the year and title unchanged for {paper_id}.")

            tags = []
            for topic in topics.values():
                value = row[topic["label"]].strip().casefold()
                if value not in ("", "x"):
                    raise ValueError(f"{location}: {topic['label']!r} must contain x or be blank.")
                if value == "x":
                    tags.append(topic["id"])
            for tag in tags:
                for parent in topics[tag]["parents"]:
                    if parent not in tags and parent not in paper.get("excluded_parent_tags", []):
                        tags.append(parent)
            assignments[paper_id] = tags

    missing = papers.keys() - assignments.keys()
    if missing:
        raise ValueError("CSV is missing papers: " + ", ".join(sorted(missing)))
    return assignments


def render_browser_data(data):
    payload = {
        "topics": [{"id": topic["id"], "label": topic["label"]} for topic in data["topics"]],
        "papers": [{"title": paper["title"], "tags": paper["tags"]} for paper in data["papers"]],
    }
    return (
        "// Generated by update-publication-topics.py; edit publication-topics.csv instead.\n"
        "window.publicationTopics = "
        + json.dumps(payload, separators=(",", ":"))
        + ";\n"
    )


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        epilog=(
            "Each keyword has its own CSV column. Mark applicable cells with x and "
            "leave other keyword cells blank. Keep id, year, and title unchanged. "
            "Topics can overlap. Parent categories are included automatically. "
            "Leave all keyword cells blank to show a paper only under All. Then run: "
            "python3 update-publication-topics.py"
        ),
    )
    parser.add_argument("--check", action="store_true", help="Check for unapplied edits without writing files.")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    data_path = root / "publication-topics.json"
    browser_path = root / "publication-topics-data.js"
    try:
        data = json.loads(data_path.read_text(encoding="utf-8"))
        assignments = read_assignments(root / "publication-topics.csv", data)
        if args.check:
            if any(set(paper["tags"]) != set(assignments[paper["id"]]) for paper in data["papers"]):
                parser.exit(1, "Unapplied topic edits. Run: python3 update-publication-topics.py\n")
            if not browser_path.is_file() or browser_path.read_text(encoding="utf-8") != render_browser_data(data):
                parser.exit(1, "Browser topic data is missing or outdated. Run: python3 update-publication-topics.py\n")
            print(f"Topic table and browser data are in sync ({len(assignments)} papers).")
            return
        for paper in data["papers"]:
            paper["tags"] = assignments[paper["id"]]
        outputs = {
            data_path: json.dumps(data, ensure_ascii=False, indent=2) + "\n",
            browser_path: render_browser_data(data),
        }
        for path, content in outputs.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                path.write_text(content, encoding="utf-8")
        print(f"Updated website topic data for {len(assignments)} papers.")
    except (OSError, ValueError, csv.Error) as error:
        parser.exit(1, f"{error}\n")


if __name__ == "__main__":
    main()
